import assert from 'node:assert/strict';
import {D1Database} from './d1-helper.mjs';
import {createConversation,writeConversationState,readConversationState} from '../functions/chat-store.js';
import {uploadChatAttachment,getChatAttachmentRecord,saveGeneratedImageOriginal} from '../functions/chat-attachments.js';
import {registerSticker,listStickers,setStickerEnabled,resolveStickerOriginal,deliverSticker} from '../functions/sticker-library.js';
const db=new D1Database();
const c=await createConversation(db,'素材','main');
const png=Uint8Array.from([137,80,78,71,13,10,26,10,0,0,0,13,73,72,68,82,0,0,0,1,0,0,0,1,8,6,0,0,0]);
const a=await uploadChatAttachment(db,c.id,{name:'wolf.png',type:'image/png',size:png.length,arrayBuffer:async()=>png.buffer});
const input={conversation_id:c.id,attachment_id:a.id,description:'摇尾巴 100%'};
await assert.rejects(()=>listStickers(db),e=>e.type==='sticker_send_denied');
await assert.rejects(()=>registerSticker(db,input,{actor:'assistant'}),e=>e.type==='sticker_add_denied');
await assert.rejects(()=>registerSticker(db,input,{actor:'assistant',allowModelAdd:true,conversationId:c.id}),e=>e.type==='sticker_add_denied');
await assert.rejects(()=>registerSticker(db,input),e=>e.type==='sticker_add_denied');
const entry=await registerSticker(db,input,{actor:'owner'});
assert.equal(entry.author,'owner');
assert.equal((await registerSticker(db,{...input,description:'duplicate'},{actor:'owner'})).id,entry.id);
assert.equal((await listStickers(db,{q:'100%'},{allowSend:true})).items[0].description,'摇尾巴 100%');
assert.equal((await listStickers(db,{q:'_'},{allowSend:true})).items.length,0);
assert.equal(JSON.stringify(await listStickers(db,{}, {allowSend:true})).includes(a.id),false);
await assert.rejects(()=>resolveStickerOriginal(db,entry.id),e=>e.type==='sticker_send_denied');
assert.deepEqual((await resolveStickerOriginal(db,entry.id,{allowSend:true})).bytes,png);
await assert.rejects(()=>setStickerEnabled(db,entry.id,false,{actor:'assistant'}),e=>e.type==='sticker_manage_denied');
await setStickerEnabled(db,entry.id,false,{actor:'owner'});
assert.equal((await listStickers(db,{}, {allowSend:true})).items.length,0);
await assert.rejects(()=>resolveStickerOriginal(db,entry.id,{allowSend:true}),e=>e.type==='sticker_unavailable');
await registerSticker(db,input,{actor:'owner'});
assert.equal((await listStickers(db,{}, {allowSend:true})).items.length,0);
await setStickerEnabled(db,entry.id,true,{actor:'owner'});

const target=await createConversation(db,'发送素材','main');
const turn={id:'turn-sticker',user:{variants:[{id:'user-sticker',content:'你好'}]},assistant:{variantsByUserVariant:{0:[{id:'assistant-sticker',content:'',finish_reason:'sticker_tool_ready'}]}}};
await writeConversationState(db,target.id,{turns:[turn]});
const delivery={conversation_id:target.id,turn_id:turn.id,user_variant_id:'user-sticker',message_id:'assistant-sticker',sticker_id:entry.id};
await assert.rejects(()=>deliverSticker(db,delivery),e=>e.type==='sticker_send_denied');
await assert.rejects(()=>deliverSticker(db,{...delivery,message_id:'wrong'},{allowSend:true}),e=>e.type==='sticker_reservation_lost');
const sent=await deliverSticker(db,delivery,{allowSend:true});
assert.notEqual(sent.attachment.id,a.id);
assert.deepEqual(new Uint8Array((await getChatAttachmentRecord(db,target.id,sent.attachment.id)).data),png);
const repeated=await deliverSticker(db,delivery,{allowSend:true});
assert.equal(repeated.reused,true);
assert.equal(repeated.attachment.id,sent.attachment.id);
const saved=(await readConversationState(db,target.id)).turns[0].assistant.variantsByUserVariant['0'][0];
assert.deepEqual(saved.attachments,[sent.attachment]);
await writeConversationState(db,target.id,{turns:[turn]});
assert.deepEqual((await readConversationState(db,target.id)).turns[0].assistant.variantsByUserVariant['0'][0].attachments,[sent.attachment]);
await assert.rejects(()=>writeConversationState(db,target.id,{turns:[]}),e=>e.type==='image_history_changed');
const gt='generated-turn',gm='generated-model';
await writeConversationState(db,c.id,{turns:[{id:gt,user:{variants:[{id:'generated-user',content:'draw'}]}}]});
const generated=await saveGeneratedImageOriginal(db,{conversationId:c.id,turnId:gt,messageId:gm,generated:{bytes:png,mime:'image/png',provider:'openrouter',requested_model:'fixture/image:free',prompt:'wolf'}});
await writeConversationState(db,c.id,{turns:[{id:gt,user:{variants:[{id:'generated-user',content:'draw'}]},assistant:{variantsByUserVariant:{0:[{id:gm,content:'',attachments:[generated.attachment]}]}}}]});
const generatedInput={conversation_id:c.id,attachment_id:generated.attachment.id,description:'模型自己画的小狼'};
await assert.rejects(()=>registerSticker(db,generatedInput,{actor:'assistant',allowModelAdd:true,conversationId:target.id}),e=>e.type==='sticker_add_denied');
const own=await registerSticker(db,generatedInput,{actor:'assistant',allowModelAdd:true,conversationId:c.id});
assert.equal(own.author,'assistant');
await db.prepare('UPDATE conversations SET deleted_at=? WHERE id=?').bind(Date.now(),c.id).run();
assert.equal((await listStickers(db,{}, {allowSend:true})).items.length,0);
await assert.rejects(()=>resolveStickerOriginal(db,entry.id,{allowSend:true}),e=>e.type==='sticker_source_unavailable');
console.log('sticker library index: ok');
