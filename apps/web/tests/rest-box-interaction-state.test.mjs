import assert from 'node:assert/strict';
import {initialInteraction,contactEvidence,emojiList,applyInteraction,pendingContacts,claimContacts} from '../elementera-mcp/deploy-pages/public/rest-box/interaction-state.mjs';
const s=initialInteraction(),ctx={eventId:'e1',windowId:'A',at:1,actor:'human',origin:'gesture',scope:'rest',cycleId:'c1',live:true,humanEnabled:true,contactRadius:.1,expectedRevision:0};
const move={kind:'move',start:s.positions.human,end:{x:.61,y:.73}};
assert.equal(contactEvidence(move.start,move.end,s.positions.model,.1),true);
assert.equal(contactEvidence(move.start,move.start,s.positions.model,.1),false);
assert.throws(()=>applyInteraction(s,move,{...ctx,editing:true}));
assert.throws(()=>applyInteraction(s,move,{...ctx,preview:true}));
const result=applyInteraction(s,move,ctx);assert.equal(result.event.data.kind,'contact');assert.equal(s.events.length,0);
assert.equal(applyInteraction(result.state,move,ctx).replayed,true);
assert.equal(pendingContacts(result.state,'rest','c1',['A']).length,1);
assert.equal(pendingContacts(result.state,'rest','c2',['A']).length,0);
assert.equal(pendingContacts(result.state,'rest','c1',['B']).length,0);
const receipt={callId:'call1',windowId:'B',scope:'rest',cycleId:'c1',visibleWindowIds:['A','B'],expectedRevision:1,responseCommitted:true};
assert.throws(()=>claimContacts(result.state,{...receipt,responseCommitted:false},['e1']));
const next=claimContacts(result.state,receipt,['e1']);assert.equal(pendingContacts(next,'rest','c1',['A']).length,0);
assert.equal(claimContacts(next,receipt,['e1']),next);
assert.deepEqual(emojiList(['🥺','👨‍👩‍👧','🇨🇳']),['🥺','👨‍👩‍👧','🇨🇳']);
assert.throws(()=>emojiList(['hello']));assert.throws(()=>emojiList(['😀','😀','😀','😀']));
assert.throws(()=>applyInteraction(next,{kind:'action',action:'sleep'},{...ctx,eventId:'e2',actor:'model',expectedRevision:2}));
console.log('interaction policy: real gesture, role, scope, replay, emoji, receipt');
