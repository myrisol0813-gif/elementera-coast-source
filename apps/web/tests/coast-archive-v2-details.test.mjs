import test from 'node:test';
import assert from 'node:assert/strict';
import { D1Database } from './d1-helper.mjs';
import { createConversation } from '../functions/chat-store.js';
import { ensureMemorySchema } from '../functions/memory-store/memory-schema.js';
import { ensureLibrarySchema } from '../functions/tidal-library.js';
import { ensureUserPortraitSchema } from '../functions/memory-store/user-portrait-store.js';
import { DETAIL_MODULES,archiveDetailPage,readArchiveLibraryCover } from '../functions/coast-archive-v2-details.js';
import { MODULES,encodeRecordObject } from '../functions/coast-archive-v2-manifest.js';
import { createArchiveSession,registerArchiveObject,putArchiveChunk,preflightArchiveSession } from '../functions/coast-archive-v2-stage.js';
test('all detail collectors run on actual schema and retain historical fields',async()=>{
 const db=new D1Database();const c=await createConversation(db,'archive details','main');
 for(const kind of Object.keys(DETAIL_MODULES))assert.ok(Array.isArray((await archiveDetailPage(db,kind)).items),kind);
 await ensureMemorySchema(db);
 await db.prepare("INSERT INTO conversation_soil_snapshots (conversation_id,turn_id,assistant_message_id,current_text,afterthoughts_json,revision,created_at) VALUES (?,?,?,?,?,?,?)").bind(c.id,'turn-1','assistant-1','原始思维壤','["余思"]',1,1).run();
 const s=(await archiveDetailPage(db,'thinking_soil_history')).items[0];
 assert.equal(s.current_text,'原始思维壤');assert.equal(s.afterthoughts_json,'["余思"]');assert.equal(s.assistant_message_id,'assistant-1');
 await ensureUserPortraitSchema(db);
 for(let i=0;i<2;i++)await db.prepare('INSERT INTO user_portrait_revisions (id,revision,before_body,after_body,confirmation_mode,created_at) VALUES (?,?,?,?,?,?)').bind('rev-'+i,i+1,'前','后'+i,'manual',i+1).run();
 const page=await archiveDetailPage(db,'user_portrait_revisions',{limit:1});const next=await archiveDetailPage(db,'user_portrait_revisions',{cursor:page.next_cursor,limit:1});
 assert.deepEqual([page.items[0].id,next.items[0].id],['rev-0','rev-1']);assert.equal(next.next_cursor,null);
 await ensureLibrarySchema(db);
 await db.prepare('INSERT INTO coast_library_books (id,title,format,created_at,updated_at) VALUES (?,?,?,?,?)').bind('book','书','epub',1,1).run();
 await db.prepare('INSERT INTO coast_library_chapters (book_id,chapter_index,title,body) VALUES (?,?,?,?)').bind('book',0,'第一章','原始章节内容').run();
 await db.prepare('INSERT INTO coast_library_covers (book_id,mime,data,size,updated_at) VALUES (?,?,?,?,?)').bind('book','image/png',new Uint8Array([1,2,3]),3,1).run();
 assert.equal((await archiveDetailPage(db,'library_chapters')).items[0].body,'原始章节内容');
 assert.deepEqual([...(await readArchiveLibraryCover(db,'book')).chunks[0]],[1,2,3]);
 await assert.rejects(()=>archiveDetailPage(db,'mailbox_messages'));
});
test('preflight checks session coverage and never declares a restore committed',async()=>{
 const db=new D1Database(),session=await createArchiveSession(db);
 const {descriptor,chunks}=await encodeRecordObject({id:'c',body:'record'});
 const record={module:'chat',id:'c',record_object:descriptor.object_sha256,media_objects:[],dependencies:[]};
 const manifest={format:'elementera-coast-archive',version:2,workspace:'backend',application_id:'com.elementeracoast.app',exported_at:'2026-01-01T00:00:00Z',modules:MODULES.map(module=>({module,coverage:module==='chat'?'complete':'unavailable',count:module==='chat'?1:0})),records:[record],objects:[descriptor]};
 assert.equal((await preflightArchiveSession(db,session.id,manifest)).ready_for_byte_verification,false);
 await registerArchiveObject(db,session.id,descriptor);
 assert.equal((await preflightArchiveSession(db,session.id,manifest)).ready_for_byte_verification,false);
 await putArchiveChunk(db,session.id,descriptor.object_sha256,0,chunks[0]);
 const ready=await preflightArchiveSession(db,session.id,manifest);
 assert.equal(ready.ready_for_byte_verification,true);assert.equal(ready.restore_supported,false);assert.equal(ready.byte_verification_pending,true);
 const extra=await encodeRecordObject({extra:true});await registerArchiveObject(db,session.id,extra.descriptor);
 assert.equal((await preflightArchiveSession(db,session.id,manifest)).ready_for_byte_verification,false);
});
