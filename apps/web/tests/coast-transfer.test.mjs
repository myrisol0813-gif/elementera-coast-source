import assert from 'node:assert/strict';
import { D1Database } from './d1-helper.mjs';
import { createConversation, writeConversationState, listConversations, readConversationState } from '../functions/chat-store.js';
import { createCalendarEntry, listCalendarEntries } from '../functions/calendar-store.js';
import { encodeTransfer, decodeTransfer } from '../functions/coast-transfer.js';
import { exportCloudTransfer, previewCloudTransfer, importCloudTransfer } from '../functions/coast-transfer-store.js';
import { routeApi } from '../functions/api-router.js';

const origin=new D1Database(), target=new D1Database();
const c=await createConversation(origin,'原始窗口');
const time='2026-11-24T12:00:00.000Z';
await writeConversationState(origin,c.id,{version:4,turns:[{id:'turn1',user:{active:1,variants:[{id:'u1',content:'旧问题',created_at:time},{id:'u2',content:'新问题',created_at:time,favorite:true}]},assistant:{activeByUserVariant:{'0':0,'1':1},variantsByUserVariant:{'0':[], '1':[{id:'a1',content:'旧回答',created_at:time,hidden:true},{id:'a2',content:'新回答',created_at:time,liked:true}]}}}]});
const cal=await createCalendarEntry(origin,{day:'2026-11-24',title:'百日',anniversary:{startDay:'2026-11-24',mode:'milestone',targetDays:100,pinned:true}});
const bundle=await exportCloudTransfer(origin);
const payload=await decodeTransfer(bundle);
assert.equal(payload.calendar[0].day,'2027-03-03');
const preview=await previewCloudTransfer(target,bundle,['chat','calendar']);
assert.equal(preview.chat.ready,1);assert.equal(preview.calendar.ready,1);assert.equal(preview.can_commit,true);
assert.equal((await listConversations(target)).length,0);
await importCloudTransfer(target,bundle,['chat','calendar']);
assert.deepEqual(await readConversationState(target,c.id),await readConversationState(origin,c.id));
assert.equal((await listCalendarEntries(target,{pinned:true}))[0].id,cal.id);
const second=await importCloudTransfer(target,bundle,['chat','calendar']);assert.equal(second.chat.existing,1);assert.equal(second.calendar.existing,1);
assert.equal((await listConversations(target)).length,1);
await assert.rejects(()=>decodeTransfer({...bundle,payload_json:bundle.payload_json.replace('新回答','损坏')}));
const invalid=structuredClone(payload);invalid.conversations[0].history.turns[0].user.active=8;
const broken=await encodeTransfer(invalid), empty=new D1Database();
assert.equal((await previewCloudTransfer(empty,broken,['chat','calendar'])).can_commit,false);
await assert.rejects(()=>importCloudTransfer(empty,broken,['chat','calendar']));
assert.equal((await listCalendarEntries(empty,{all:true})).length,0);
const owner={exp:Math.floor(Date.now()/1000)+60};
const req=(path,body)=>new Request('https://coast.test/api/transfer/v1'+path,{method:'POST',headers:{Origin:'https://coast.test','Content-Type':'application/json'},body:JSON.stringify(body)});
assert.equal((await routeApi(req('/preview',{bundle,modules:['chat']}),{COAST_CHAT_DB:empty},null)).status,401);
assert.equal((await routeApi(req('/import',{bundle,modules:['chat']}),{COAST_CHAT_DB:empty},owner)).status,400);
assert.equal((await routeApi(req('/import',{bundle,modules:['chat'],confirm:true}),{COAST_CHAT_DB:empty},owner)).status,200);
console.log('portable transfer: checksum, branches, calendar, preview, idempotency, authorization, blocked batch: ok');
