import assert from 'node:assert/strict';
import { D1Database } from './d1-helper.mjs';
import { createConversation, readConversationState, writeConversationState, listConversations, deleteConversation } from '../functions/chat-store.js';
import { encodeTransfer, decodeTransfer } from '../functions/transfer-codec.js';
import { exportTransferChat, previewTransferChat, importTransferChat } from '../functions/transfer-chat-store.js';

const db = new D1Database();
const c = await createConversation(db,'中文测试');
const variant = (id,content,extra={}) => ({id,content,created_at:'2026-11-24T12:00:00Z',...extra});
await writeConversationState(db,c.id,{turns:[{id:'t1',user:{active:1,variants:[variant('u1','旧问题'),variant('u2','新问题',{favorite:true})]},
 assistant:{activeByUserVariant:{'1':1},variantsByUserVariant:{'1':[variant('a1','隐藏旧回复',{hidden:true}),variant('a2','回复',{model_id:'model/test',liked:true})]}}}]});
const bundle = await exportTransferChat(db,[c.id]);
const payload = await decodeTransfer(bundle);
assert.equal(payload.source.mode,'backend');
const target = new D1Database();
const preview = await previewTransferChat(target,bundle);
assert.equal(preview.variants,4);
assert.equal((await listConversations(target)).length,0);
await assert.rejects(importTransferChat(target,bundle),/确认/);
const result = await importTransferChat(target,bundle,{confirm:true,acceptOmissions:true});
assert.equal(result.imported_conversation_ids.length,1);
const id = result.imported_conversation_ids[0];
const restored = await readConversationState(target,id);
assert.equal(restored.turns[0].user.active,1);
assert.equal(restored.turns[0].user.variants[1].favorite,true);
assert.equal(restored.turns[0].assistant.variantsByUserVariant['1'][0].hidden,true);
assert.equal(restored.turns[0].assistant.variantsByUserVariant['1'][1].content,'回复');
const changed = {...restored, turns:[]};
await writeConversationState(target,id,changed);
assert.equal((await importTransferChat(target,bundle,{confirm:true,acceptOmissions:true})).previously_imported,1);
assert.equal((await readConversationState(target,id)).turns.length,0);
await deleteConversation(target,id);
assert.equal((await importTransferChat(target,bundle,{confirm:true,acceptOmissions:true})).deleted_previously_imported,1);
assert.equal((await listConversations(target)).length,0);
await assert.rejects(decodeTransfer({...bundle,payload_json:bundle.payload_json.replace('回复','篡改')}),/校验/);
const altered = structuredClone(payload);
altered.modules.daily = {diaries:[]};
const multi = await encodeTransfer(altered);
assert.deepEqual((await previewTransferChat(new D1Database(),multi)).unselected_modules,['daily']);
await assert.rejects(importTransferChat(new D1Database(),multi,{confirm:true}),/明确确认/);
const oversized = structuredClone(payload);
const t = oversized.modules.chat.conversations[0].history.turns[0];
oversized.modules.chat.conversations[0].history.turns = Array.from({length:401},(_,i)=>({...t,id:'turn'+i}));
await assert.rejects(previewTransferChat(new D1Database(),await encodeTransfer(oversized)),/400/);
console.log('transfer chat: checksum, preview, branches, copy, duplicate/delete safety and limits ok');
