import test from 'node:test';
import assert from 'node:assert/strict';
import { D1Database } from './d1-helper.mjs';
import { createConversation } from '../functions/chat-store.js';
import { uploadChatAttachment, getChatAttachmentRecord } from '../functions/chat-attachments.js';
import { ensureDogtalkSchema } from '../functions/dogtalk-store.js';
import { listArchiveAttachments, readArchiveAttachment, prepareArchiveAttachment, listArchiveDogtalk } from '../functions/coast-archive-v2-media.js';
test('archive inventory includes unbound attachments and restores original bytes and ids in a transaction',async()=>{
  const db=new D1Database(),target=new D1Database();
  const c=await createConversation(db,'archive test','main');
  const tc=await createConversation(target,'target test','main');
  const bytes=new Uint8Array(2200123).fill(17);bytes[bytes.length-1]=91;
  const a=await uploadChatAttachment(db,c.id,{name:'test.bin',type:'application/octet-stream',size:bytes.length,arrayBuffer:async()=>bytes.buffer});
  const b=await uploadChatAttachment(db,c.id,{name:'second.bin',type:'application/octet-stream',size:1,arrayBuffer:async()=>new Uint8Array([1]).buffer});
  const first=await listArchiveAttachments(db,{limit:1});const second=await listArchiveAttachments(db,{cursor:first.next_cursor,limit:1});
  assert.deepEqual(new Set([first.items[0].id,second.items[0].id]),new Set([a.id,b.id]));assert.equal(second.next_cursor,null);
  const item=await readArchiveAttachment(db,c.id,a.id);assert.equal(item.chunks.length,3);
  const metadata={...item.metadata,conversation_id:tc.id};const plan={conversationIds:new Set([tc.id])};
  const damaged=item.chunks.map(x=>x.slice());damaged[1][0]=3;
  await assert.rejects(()=>prepareArchiveAttachment(target,metadata,item.descriptor,damaged,plan));
  assert.equal((await listArchiveAttachments(target)).items.length,0);
  const statements=await prepareArchiveAttachment(target,metadata,item.descriptor,item.chunks,plan);
  assert.equal((await listArchiveAttachments(target)).items.length,0,'preparation cannot publish records');
  await target.batch(statements);
  const restored=await getChatAttachmentRecord(target,tc.id,a.id);assert.deepEqual(new Uint8Array(restored.data),bytes);
  assert.equal(restored.id,a.id);assert.equal(restored.created_at,item.metadata.created_at);
  await assert.rejects(()=>prepareArchiveAttachment(target,metadata,item.descriptor,item.chunks,plan));
  await assert.rejects(()=>readArchiveAttachment(db,tc.id,a.id));
});
test('historical snapshot export retains parent records, owner isolation and pagination',async()=>{
  const db=new D1Database();const c=await createConversation(db,'snapshot test','main');
  await ensureDogtalkSchema(db);
  const parent="INSERT INTO coast_mystic_dogtalk (id,type,owner,room_scope,scope_key,conversation_id,body,created_at,updated_at) VALUES (?,'mystic_dogtalk',?,'conversation',?,?,'body',1,1)";
  const snap="INSERT INTO coast_mystic_dogtalk_snapshots (id,dogtalk_id,owner,room_scope,scope_key,conversation_id,source_type,source_id,body,created_at) VALUES (?,?,?,'conversation',?,?,'message',?,'history',1)";
  await db.prepare(parent).bind('p','owner','conversation:'+c.id,c.id).run();
  await db.prepare(parent).bind('visitor','unrelated','conversation:'+c.id,c.id).run();
  for(const [id,p,owner] of [['s1','p','owner'],['s2','p','owner'],['s3','visitor','unrelated']])await db.prepare(snap).bind(id,p,owner,'conversation:'+c.id,c.id,'msg-'+id).run();
  const p=await listArchiveDogtalk(db,{kind:'records'});assert.deepEqual(p.items.map(x=>x.id),['p']);
  const a=await listArchiveDogtalk(db,{limit:1});const b=await listArchiveDogtalk(db,{limit:1,cursor:a.next_cursor});
  assert.deepEqual([a.items[0].id,b.items[0].id],['s1','s2']);assert.equal(b.next_cursor,null);assert.equal(a.items[0].owner,'owner');assert.equal(a.items[0].dogtalk_id,'p');assert.equal(a.items[0].body,'history');
});
