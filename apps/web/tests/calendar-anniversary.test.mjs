import assert from 'node:assert/strict';
import { anniversaryCalendarDay, anniversaryStatus } from '../functions/calendar-anniversary.js';

const elapsed = { startDay: '2026-11-24', mode: 'elapsed' };
assert.deepEqual(anniversaryStatus(elapsed, '2026-11-23'), { phase: 'upcoming', days: 1, day: elapsed.startDay });
assert.equal(anniversaryStatus(elapsed, '2026-11-24').days, 1);
assert.equal(anniversaryStatus(elapsed, '2026-11-25').days, 2);
const milestone = { ...elapsed, mode: 'milestone', targetDays: 100 };
assert.equal(anniversaryCalendarDay(milestone), '2027-03-03');
assert.equal(anniversaryCalendarDay({ ...milestone, targetDays: 1 }), elapsed.startDay);
assert.deepEqual(anniversaryStatus(milestone, '2027-03-03'), { phase: 'today', days: 0, day: '2027-03-03' });
assert.deepEqual(anniversaryStatus(milestone, '2027-03-04'), { phase: 'past', days: 1, day: '2027-03-03' });
assert.equal(anniversaryStatus(milestone, '2027-03-02').days, 1);
const yearly = { startDay: '2024-02-29', mode: 'yearly' };
assert.equal(anniversaryStatus(yearly, '2024-02-29').phase, 'today');
assert.equal(anniversaryStatus(yearly, '2025-02-28').day, '2028-02-29');
assert.equal(anniversaryStatus(yearly, '2023-01-01').day, '2024-02-29');
assert.equal(anniversaryStatus({ ...yearly, startDay: '2196-02-29' }, '2196-03-01').phase, 'no_future_occurrence');
assert.throws(() => anniversaryCalendarDay({ ...elapsed, startDay: '2026-02-29' }), RangeError);
assert.throws(() => anniversaryCalendarDay({ ...elapsed, mode: 'unknown' }), RangeError);
assert.throws(() => anniversaryCalendarDay({ ...milestone, targetDays: 0 }), RangeError);
assert.throws(() => anniversaryCalendarDay({ ...milestone, targetDays: 1.5 }), RangeError);
assert.throws(() => anniversaryCalendarDay({ ...elapsed, targetDays: 2 }), RangeError);
assert.throws(() => anniversaryCalendarDay({ ...milestone, startDay: '2200-12-31', targetDays: 2 }), RangeError);
console.log('anniversary calendar date contract: ok');

// Existing records remain unchanged; pinned and monthly views resolve the same record.
import { D1Database } from './d1-helper.mjs';
import { createCalendarEntry, listCalendarEntries, updateCalendarEntry, deleteCalendarEntry } from '../functions/calendar-store.js';
import { routeApi } from '../functions/api-router.js';
const db = new D1Database();
const ordinary = await createCalendarEntry(db, { day: '2026-11-24', title: '旧日程' });
assert.equal(Object.hasOwn(ordinary, 'anniversary'), false);
const ann = { ...milestone, pinned: true };
const created = await createCalendarEntry(db, { day: elapsed.startDay, title: '第一百天', anniversary: ann });
assert.equal(created.day, '2027-03-03');
assert.deepEqual(created.anniversary, ann);
assert.equal((await listCalendarEntries(db, { pinned: true }))[0].id, created.id);
assert.equal((await listCalendarEntries(db, { month: '2027-03' }))[0].id, created.id);
assert.equal((await updateCalendarEntry(db, created.id, { title: '新名称' })).day, created.day);
await assert.rejects(() => updateCalendarEntry(db, created.id, { day: '2027-03-04' }), e => e.type === 'anniversary_conflict');
await updateCalendarEntry(db, created.id, { anniversary: { ...ann, pinned: false } });
assert.deepEqual(await listCalendarEntries(db, { pinned: true }), []);
assert.equal((await listCalendarEntries(db, { month: '2027-03' }))[0].id, created.id);
await updateCalendarEntry(db, created.id, { anniversary: { ...yearly, targetDays: null, pinned: true } });
assert.equal((await listCalendarEntries(db, { month: '2027-02' })).length, 0);
assert.equal((await listCalendarEntries(db, { month: '2028-02' }))[0].id, created.id);
const owner = { exp: Math.floor(Date.now() / 1000) + 60 };
const request = () => new Request('https://coast.test/api/calendar/entries?pinned=1');
assert.equal((await routeApi(request(), { COAST_CHAT_DB: db }, null)).status, 401);
const response = await routeApi(request(), { COAST_CHAT_DB: db }, owner);
assert.equal(response.status, 200);
assert.equal((await response.json()).entries[0].id, created.id);
await deleteCalendarEntry(db, created.id);
assert.deepEqual(await listCalendarEntries(db, { pinned: true }), []);
assert.equal((await listCalendarEntries(db, { month: '2026-11' }))[0].id, ordinary.id);
assert.equal(db.database.prepare("SELECT COUNT(*) AS n FROM schema_migrations WHERE id = 'calendar-anniversary-v1'").get().n, 1);
console.log('anniversary persistence and owner API: ok');

const statusDb = new D1Database();
await createCalendarEntry(statusDb, { day: elapsed.startDay, title: '日期状态', anniversary: { ...elapsed, pinned: true } });
const statusRequest = day => new Request('https://coast.test/api/calendar/entries?pinned=1&today=' + day);
const statusReply = await routeApi(statusRequest('2026-11-24'), { COAST_CHAT_DB: statusDb }, owner);
assert.equal((await statusReply.json()).entries[0].status.days, 1);
assert.equal((await routeApi(statusRequest('2026-02-29'), { COAST_CHAT_DB: statusDb }, owner)).status, 400);
