import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const pages=new URL('../elementera-mcp/deploy-pages/',import.meta.url);
const studio=new URL('public/rest-box/',pages);
const read=async (p,root=studio)=>readFile(new URL(p,root),'utf8');
const sw=await read('service-worker.js',pages);
const list=[...sw.matchAll(/['"]\/public\/rest-box\/([^'"]+)['"]/g)].map(m=>m[1]).filter(p=>p.length);
const cached=new Set(list);
const originals=JSON.parse(await read('art/v1/fidelity.json'));
for(const {path} of originals.expected) assert.ok(cached.has('art/v1/'+path),'uncached '+path);
for(const p of cached) await read(p);
for(const p of ['room-lab.html','room-lab.mjs','room-state.mjs','room-renderer.mjs','creature-state.mjs','creature-renderer.mjs','creature-editor.mjs','studio-archive.mjs']) assert.ok(cached.has(p),p);
const html=await read('room-lab.html');
assert.match(html,/coast-room-studio/);
assert.match(html,/room-lab\.mjs/);
const js=await read('room-lab.mjs');
assert.match(js,/localStorage\.setItem/);
assert.match(js,/localStorage\.getItem/);
assert.match(js,/mountRoomStudio/);
assert.match(js,/var\(--surface/);
assert.match(js,/disconnectedCallback/);
assert.match(js,/restoreFailed/);
const daily=await read('public/features/daily.js',pages);
assert.match(daily,/coast-room-studio/);
assert.doesNotMatch(daily,/<iframe/);
const gradle=await readFile(new URL('../../android/app/build.gradle.kts',import.meta.url),'utf8');
assert.match(gradle,/dependsOn\(prepareRestStudio\)/);
assert.match(gradle,/art\/v1\/\*\*/);
const native=await readFile(new URL('../../android/app/src/main/kotlin/com/elementeracoast/app/feature/daily/PetScreen.kt',import.meta.url),'utf8');
assert.doesNotMatch(native,/WebView|AndroidView|room-lab\.html|android\.webkit/);
assert.match(native,/NativeRestScene\(/);
assert.match(native,/SnowLetterSurface/);
assert.match(native,/verticalScroll/);
assert.match(gradle,/compileRestNativeSprites/);
assert.doesNotMatch(gradle,/include\("room-lab\.html"/);
const scene=await readFile(new URL('../../android/app/src/main/kotlin/com/elementeracoast/app/feature/daily/NativeRestScene.kt',import.meta.url),'utf8');
assert.match(scene,/Canvas\(/);
assert.match(scene,/catalogue\.hitTest/);
assert.match(native,/ActivityResultContracts\.CreateDocument/);
assert.match(native,/ActivityResultContracts\.OpenDocument/);
console.log('rest studio offline asset and app entry contracts checked');

const {verifyStudio,captureStudio,restoreStudioArchive,studioFromEnvelope,STUDIO_KEY}=await import(new URL('studio-archive.mjs',studio));
const {buildCatalogue,newLayout,editLayout}=await import(new URL('room-state.mjs',studio));
const {newHousehold}=await import(new URL('creature-state.mjs',studio));
const docs=await Promise.all(['rooms/living.json','rooms/study.json','rooms/bedroom.json','extras/afternoon.json','extras/stationery.json','color-presets.json','creatures/appearance.json'].map(async p=>JSON.parse(await read('art/v1/'+p))));
const art={catalogue:buildCatalogue(docs.slice(0,3),docs.slice(3,5),docs[5]),appearance:docs[6].bodies};
const original={version:1,layout:newLayout(art.catalogue),household:newHousehold(art.appearance),room:'living',pets:true,reducedMotion:false,poseChoices:{}};
const changed={...original,room:'study',pets:false,reducedMotion:true,poseChoices:{study:{model:'none'}},layout:editLayout(original.layout,art.catalogue,'living',{type:'add',assetId:'extra-laptop',id:'test-laptop'})};
const values=new Map([[STUDIO_KEY,JSON.stringify(original)],['other','untouched']]);
const storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)};
const fixture=await verifyStudio(changed,art);
assert.deepEqual(await captureStudio(storage,art),await verifyStudio(original,art));
const preview=await restoreStudioArchive(fixture,false,storage,art);
assert.equal(preview.conflicts,1);assert.equal(values.get(STUDIO_KEY),JSON.stringify(original));
await restoreStudioArchive(fixture,true,storage,art);
assert.deepEqual(await captureStudio(storage,art),fixture);
assert.equal(values.get(STUDIO_KEY+'.archive-previous'),JSON.stringify(original));
assert.equal(values.get('other'),'untouched');
assert.equal((await restoreStudioArchive(fixture,true,storage,art)).existing,1);
await assert.rejects(()=>restoreStudioArchive({...fixture,version:99},true,storage,art));
assert.deepEqual(await captureStudio(storage,art),fixture);
const record={module:'appearance',id:'device-basic-settings',dependencies:[],media_objects:[]};
assert.deepEqual(studioFromEnvelope(record,{kind:'device_basic_settings',data:{basic_settings:{},rest_studio:fixture}}),fixture);
assert.throws(()=>studioFromEnvelope({...record,id:'unknown'},{kind:'device_basic_settings',data:{rest_studio:fixture}}));
assert.equal(studioFromEnvelope({...record,module:'chat'},{kind:'device_basic_settings',data:{rest_studio:fixture}}),null);
console.log('studio archive: verified round trip, preview isolation, preserved old save and device-only envelope');
